"""M4 browser acceptance against the explicit offline FIXTURE service on port 3111."""
from pathlib import Path
import os
from playwright.sync_api import sync_playwright, expect
out = Path('data/browser-evidence/M4')
out.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, channel=os.environ.get('SCOUT_BROWSER_CHANNEL', 'msedge'))
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, reduced_motion='reduce')
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:3111/#/login')
    page.wait_for_load_state('networkidle')
    page.get_by_label('管理员密码').fill('browser-fixture-only')
    page.get_by_role('button', name='进入工作台').click()
    page.get_by_role('button', name='设置').click()
    panel = page.get_by_role('region', name='模型配置诊断')
    panel.get_by_text('配置版本 1', exact=False).wait_for()
    expect(panel.get_by_role('button', name='主动连接测试')).to_be_disabled()
    page.get_by_label('模型名称', exact=True).fill('fixture-model-m4')
    page.get_by_role('button', name='保存设置').click()
    panel.get_by_text('配置版本 2', exact=False).wait_for()
    expect(panel.locator('.probe-history li')).to_have_count(0)
    page.screenshot(path=str(out/'diagnostics-desktop.png'), full_page=True)
    page.get_by_label('我理解：将发起一次真实模型请求，可能计费。').check()
    panel.get_by_role('button', name='主动连接测试').click()
    panel.get_by_text('演示数据 · 已完成', exact=True).wait_for()
    expect(panel.locator('.probe-history li')).to_have_count(1)
    panel.get_by_text('本次服务配置下最近测试成功', exact=False).wait_for()
    page.get_by_label('模型名称', exact=True).fill('unsaved-model')
    panel.get_by_text('存在未保存编辑', exact=False).wait_for()
    expect(panel.get_by_role('button', name='主动连接测试')).to_be_disabled()
    page.reload()
    page.get_by_role('button', name='设置').click()
    panel.get_by_text('演示数据 · 已完成', exact=True).wait_for()
    expect(page.get_by_label('模型名称', exact=True)).to_have_value('fixture-model-m4')
    expect(panel.locator('.probe-history li')).to_have_count(1)
    # Explicit second attempt must fail cooldown without sending another provider request.
    page.get_by_label('我理解：将发起一次真实模型请求，可能计费。').check()
    panel.get_by_role('button', name='主动连接测试').click()
    panel.get_by_role('alert').filter(has_text='MODEL_TEST_COOLDOWN').wait_for()
    expect(panel.locator('.probe-history li')).to_have_count(1)
    assert 'fixture-model-secret' not in page.locator('body').inner_text()
    page.screenshot(path=str(out/'test-result-desktop.png'), full_page=True)
    page.set_viewport_size({'width': 390, 'height': 844})
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.screenshot(path=str(out/'test-result-mobile.png'), full_page=True)
    assert errors == [], errors
    browser.close()
print('PASS M4 FIXTURE: local checks, save revision, consent, probe, dirty guard, reload history, cooldown, mobile; no page errors')
