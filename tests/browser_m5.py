"""Explicit FIXTURE flow, with no real GitHub or model transport."""
from pathlib import Path
import os
from playwright.sync_api import sync_playwright, expect
out=Path('data/browser-evidence/M5')
out.mkdir(parents=True,exist_ok=True)
base='http://127.0.0.1:3113'
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,channel=os.environ.get('SCOUT_BROWSER_CHANNEL','msedge'))
    page=browser.new_page(viewport={'width':1440,'height':1000},reduced_motion='reduce')
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(base+'/#/login')
    page.wait_for_load_state('networkidle')
    page.get_by_label('管理员密码').fill('browser-fixture-only')
    page.get_by_role('button',name='进入工作台').click()
    page.get_by_role('button',name='机会发现').click()
    page.get_by_role('heading',name='发现下一次贡献').wait_for()
    expect(page.get_by_role('button',name='立即发现')).to_be_disabled()
    page.get_by_label('偏好语言（逗号分隔）').fill('Java, Python')
    page.get_by_role('button',name='保存画像',exact=True).click()
    page.get_by_text('技术画像 v1',exact=True).wait_for()
    page.get_by_role('button',name='立即发现').click()
    card=page.locator('.candidate-card').first
    card.wait_for()
    expect(card).to_contain_text('FIXTURE')
    assert page.locator('img[src=x]').count()==0
    card.get_by_role('button',name='收藏',exact=True).click()
    expect(card).to_contain_text('已收藏')
    card.get_by_role('button',name='忽略',exact=True).click()
    expect(page.locator('.candidate-card')).to_have_count(0)
    page.get_by_label('候选筛选').select_option('ignored')
    card.wait_for()
    expect(card).to_contain_text('已收藏')
    card.get_by_role('button',name='重新启用').click()
    page.get_by_label('候选筛选').select_option('active')
    card.wait_for()
    card.get_by_role('button',name='排除仓库').click()
    expect(page.locator('.candidate-card')).to_have_count(0)
    page.get_by_role('button',name='编辑技术画像').click()
    page.get_by_role('button',name='101 × 移除').click()
    page.get_by_role('button',name='保存画像',exact=True).click()
    page.get_by_text('技术画像 v3',exact=True).wait_for()
    page.get_by_role('button',name='立即发现').click()
    card.wait_for()
    card.locator('.candidate-title').click()
    detail=page.get_by_role('region',name='候选详情')
    detail.get_by_role('button',name='选择并复核来源').click()
    detail.get_by_text('WAITING_SOURCE_CONFIRMATION',exact=False).wait_for()
    expect(detail.get_by_role('button',name='开始深入分析（可能计费）',exact=True)).to_be_disabled()
    page.screenshot(path=str(out/'candidate-desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.screenshot(path=str(out/'candidate-mobile.png'),full_page=True)
    page.set_viewport_size({'width':1440,'height':1000})
    detail.get_by_label('我已核对重复修复风险，确认开始深入分析可能计费。').check()
    detail.get_by_role('button',name='开始深入分析（可能计费）',exact=True).click()
    detail.get_by_role('button',name='打开关联分析任务').click()
    page.get_by_text('FIXTURE 有限来源分析',exact=True).wait_for()
    page.get_by_role('button',name='机会发现').click()
    page.get_by_role('button',name='编辑技术画像').click()
    page.get_by_label('开启每日定时发现').check()
    page.get_by_role('button',name='保存画像',exact=True).click()
    page.locator('.profile-strip').get_by_text('下次',exact=False).wait_for()
    page.reload()
    page.get_by_role('button',name='机会发现').click()
    page.locator('.profile-strip').get_by_text('下次',exact=False).wait_for()
    page.get_by_role('button',name='编辑技术画像').click()
    page.get_by_label('开启每日定时发现').uncheck()
    page.get_by_role('button',name='保存画像',exact=True).click()
    page.locator('.profile-strip').get_by_text('不会自动扫描',exact=False).wait_for()
    page.get_by_label('候选筛选').select_option('all')
    expect(page.locator('.candidate-card')).to_have_count(1)
    expect(page.locator('.candidate-card')).to_contain_text('已收藏')
    assert errors==[],errors
    assert 'fixture-model-secret' not in page.locator('body').inner_text()
    browser.close()
print('PASS M5 FIXTURE: profile/save, discovery, stable candidate, favorite/ignore/enable/exclude, source risk consent, analysis link, scheduling persistence, mobile and no JS errors')
